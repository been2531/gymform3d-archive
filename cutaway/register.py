"""Layer registration for cutaway reels.

Every deeper layer (outer muscle, bone/cartilage) is generated by *editing* the
skin image, so the pose is the same but the generator may shift / rescale it a
little and may add letterbox bars.  We:

  1. trim near-black letterbox bars,
  2. build a soft foreground (silhouette) mask for skin and layer,
  3. initialise a similarity transform from mask moments (centroid + sqrt(area)),
  4. refine with OpenCV ECC (MOTION_AFFINE) on blurred masks,
  5. warp the layer onto the skin canvas and score it with a symmetric
     silhouette-edge chamfer distance (median, p90) in skin-canvas px.

The macro layer is an edit of a square crop of the bone layer, so it is
registered against that crop with ECC on gray intensity (same content), and its
placement inside the bone canvas is stored as a crop box.

Output: <asset_dir>/registered/{skin,outer,bone}.png (same size as skin),
        macro.png, and registration.json with transforms + scores.
"""
from __future__ import annotations

import json
import os
import sys

import cv2
import numpy as np


def load_rgb(p):
    im = cv2.imread(p, cv2.IMREAD_COLOR)
    if im is None:
        raise FileNotFoundError(p)
    return cv2.cvtColor(im, cv2.COLOR_BGR2RGB)


def trim_bars(im, thr=10):
    """Drop fully-dark letterbox rows/cols at the borders (generator padding)."""
    g = im.max(axis=2)
    rows = np.where(np.percentile(g, 99, axis=1) > thr)[0]
    cols = np.where(np.percentile(g, 99, axis=0) > thr)[0]
    if len(rows) == 0 or len(cols) == 0:
        return im, (0, 0)
    y0, y1, x0, x1 = rows[0], rows[-1] + 1, cols[0], cols[-1] + 1
    return im[y0:y1, x0:x1].copy(), (int(x0), int(y0))


def fg_mask(im):
    """Soft silhouette of the subject against a dark studio background."""
    lum = cv2.cvtColor(im, cv2.COLOR_RGB2GRAY).astype(np.float32)
    lum = cv2.GaussianBlur(lum, (0, 0), max(2.0, im.shape[1] / 200))
    t, _ = cv2.threshold(lum.astype(np.uint8), 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)
    t = max(14.0, min(float(t) * 0.55, 60.0))       # low-key renders: keep dim rims
    m = (lum > t).astype(np.uint8)
    n, lab, st, _ = cv2.connectedComponentsWithStats(m, 8)
    if n > 1:
        k = 1 + int(np.argmax(st[1:, cv2.CC_STAT_AREA]))
        m = (lab == k).astype(np.uint8)
    # fill holes
    # pad with a 1-px background frame so every border-touching background pocket is
    # reached by the flood (otherwise pockets cut off by the limb get filled as "holes")
    ff = cv2.copyMakeBorder(m, 1, 1, 1, 1, cv2.BORDER_CONSTANT, value=0)
    h, w = ff.shape
    msk = np.zeros((h + 2, w + 2), np.uint8)
    cv2.floodFill(ff, msk, (0, 0), 1)
    m = m | (1 - ff[1:-1, 1:-1])
    return m


def _moments(m):
    M = cv2.moments(m, binaryImage=True)
    return M["m10"] / M["m00"], M["m01"] / M["m00"], M["m00"]


def edges(m):
    return cv2.morphologyEx(m, cv2.MORPH_GRADIENT, np.ones((3, 3), np.uint8)) > 0


def chamfer(ma, mb):
    """Symmetric silhouette-edge distance (median, p90) in px.  Image-border edges are ignored."""
    ea, eb = edges(ma), edges(mb)
    h, w = ma.shape
    border = np.zeros_like(ea)
    b = 6
    border[:b] = border[-b:] = True
    border[:, :b] = border[:, -b:] = True
    ea &= ~border
    eb &= ~border
    da = cv2.distanceTransform((~eb).astype(np.uint8), cv2.DIST_L2, 5)
    db = cv2.distanceTransform((~ea).astype(np.uint8), cv2.DIST_L2, 5)
    d = np.concatenate([da[ea], db[eb]])
    if d.size == 0:
        return 999.0, 999.0
    return float(np.median(d)), float(np.percentile(d, 90))


def _iou(a, b):
    i = np.minimum(a, b).sum()
    u = np.maximum(a, b).sum()
    return float(i / max(u, 1e-6))


def register_silhouette(skin, layer, max_shift=0.06, max_scale=0.08, max_rot=3.0):
    """Constrained similarity search around the identity prior.

    The generator was given the skin image as the edit reference with the same
    aspect ratio, so the prior is: layer resized to the skin canvas.  We search
    a small window (scale +-8 %, shift +-6 % of width, rot +-3 deg) for the best
    soft-silhouette IoU and only move off identity if it clearly helps."""
    H, W = skin.shape[:2]
    lh, lw = layer.shape[:2]
    S0 = np.array([[W / lw, 0, 0], [0, H / lh, 0]], np.float32)
    lay0 = cv2.warpAffine(layer, S0, (W, H), flags=cv2.INTER_AREA)
    ms, ml = fg_mask(skin), fg_mask(lay0)
    k = 200.0 / W
    a = cv2.resize(cv2.GaussianBlur(ms.astype(np.float32), (0, 0), 5), None, fx=k, fy=k, interpolation=cv2.INTER_AREA)
    b = cv2.resize(cv2.GaussianBlur(ml.astype(np.float32), (0, 0), 5), None, fx=k, fy=k, interpolation=cv2.INTER_AREA)
    h, w = a.shape
    c = (w / 2, h / 2)
    best = (_iou(a, b), 1.0, 0.0, 0.0, 0.0)
    base_iou = best[0]
    shifts = np.linspace(-max_shift * w, max_shift * w, 13)
    for sc in np.linspace(1 - max_scale, 1 + max_scale, 9):
        for rot in (-max_rot, 0.0, max_rot):
            R = cv2.getRotationMatrix2D(c, rot, sc)
            for tx in shifts:
                for ty in shifts:
                    Rm = R.copy(); Rm[0, 2] += tx; Rm[1, 2] += ty
                    v = _iou(a, cv2.warpAffine(b, Rm, (w, h)))
                    if v > best[0]:
                        best = (v, sc, rot, tx, ty)
    v, sc, rot, tx, ty = best
    if v - base_iou < 0.01:
        sc, rot, tx, ty = 1.0, 0.0, 0.0, 0.0
    R = cv2.getRotationMatrix2D((W / 2, H / 2), rot, sc)
    R[0, 2] += tx / k; R[1, 2] += ty / k
    A = (np.vstack([R, [0, 0, 1]]) @ np.vstack([S0, [0, 0, 1]]))[:2].astype(np.float32)
    wm = cv2.warpAffine(fg_mask(layer), A, (W, H), flags=cv2.INTER_NEAREST)
    return A, chamfer(ms, wm), ms, {"iou_identity": round(base_iou, 4), "iou_best": round(max(v, base_iou), 4),
                                    "scale": round(float(sc), 3), "rot_deg": float(rot),
                                    "shift_px": [round(tx / k, 1), round(ty / k, 1)]}


def unsharp(im, amount=0.45, sigma=1.4):
    b = cv2.GaussianBlur(im, (0, 0), sigma)
    return cv2.addWeighted(im, 1 + amount, b, -amount, 0)


def local_warp(img, src_pt, dst_pt, sigma):
    """Smooth landmark warp: content at src_pt moves to dst_pt, falling off with a
    Gaussian of width sigma (px).  Inverse map: out(p) = in(p - d(p))."""
    h, w = img.shape[:2]
    d = np.array(dst_pt, np.float32) - np.array(src_pt, np.float32)
    ys, xs = np.mgrid[0:h, 0:w].astype(np.float32)
    g = np.exp(-(((xs - dst_pt[0]) ** 2 + (ys - dst_pt[1]) ** 2) / (2 * sigma ** 2)))
    return cv2.remap(img, xs - d[0] * g, ys - d[1] * g, cv2.INTER_CUBIC, borderMode=cv2.BORDER_REPLICATE)


def register_macro(crop_rgb, macro_rgb):
    """Macro is an edit of a square crop: align by ECC on gray intensity."""
    g1 = cv2.cvtColor(crop_rgb, cv2.COLOR_RGB2GRAY).astype(np.float32) / 255
    g2 = cv2.cvtColor(cv2.resize(macro_rgb, (crop_rgb.shape[1], crop_rgb.shape[0]), interpolation=cv2.INTER_AREA),
                      cv2.COLOR_RGB2GRAY).astype(np.float32) / 255
    g1 = cv2.GaussianBlur(g1, (0, 0), 3)
    g2 = cv2.GaussianBlur(g2, (0, 0), 3)
    warp = np.eye(2, 3, dtype=np.float32)
    try:
        cc, warp = cv2.findTransformECC(g1, g2, warp, cv2.MOTION_AFFINE,
                                        (cv2.TERM_CRITERIA_EPS | cv2.TERM_CRITERIA_COUNT, 300, 1e-6), None, 5)
    except cv2.error:
        cc = 0.0
    shift = float(np.hypot(warp[0, 2], warp[1, 2]))
    return warp, float(cc), shift


def run(asset_dir: str, joint: str | None = None) -> dict:
    """asset_dir holds skin_raw.*, outer_raw.*, bone_raw.* and (optionally, after the
    macro edit) macro_raw.* + macro_crop.json {"box_canvas": [x0, y0, size]} = the square
    of the REGISTERED bone canvas that was given to the generator as the macro reference."""
    import landmarks as LM

    def find(stem, required=True):
        for ext in (".png", ".jpg", ".jpeg", ".webp"):
            p = os.path.join(asset_dir, stem + ext)
            if os.path.exists(p):
                return p
        if required:
            raise FileNotFoundError(os.path.join(asset_dir, stem + ".*"))
        return None

    joint = joint or os.path.basename(os.path.normpath(asset_dir))
    cfg = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "joint_landmarks.json"))).get(joint)
    out_dir = os.path.join(asset_dir, "registered")
    os.makedirs(out_dir, exist_ok=True)
    skin = load_rgb(find("skin_raw"))   # the exact image given to the generator as reference
    H, W = skin.shape[:2]
    rep = {"canvas": [W, H], "layers": {}, "joint": joint}
    cv2.imwrite(os.path.join(out_dir, "skin.png"), cv2.cvtColor(skin, cv2.COLOR_RGB2BGR))
    for name in ("outer", "bone"):
        raw = load_rgb(find(f"{name}_raw"))
        A, (med, p90), _, info = register_silhouette(skin, raw)
        warped = cv2.warpAffine(raw, A, (W, H), flags=cv2.INTER_CUBIC, borderMode=cv2.BORDER_CONSTANT,
                                borderValue=(6, 6, 7))
        warped = unsharp(warped)
        if name == "bone" and cfg and cfg.get("landmark") == "patella_vs_skin_bump":
            before = LM.knee_report(skin, warped, cfg["front"])
            lm = {"before": before}
            if before.get("patella_apex"):
                mag = float(np.hypot(before["dx"], before["dy"]))
                lm["warp_canvas_px"] = round(mag, 1)
                lm["warp_ok"] = mag <= cfg["max_warp_canvas_px"]
                if lm["warp_ok"]:
                    warped = local_warp(warped, before["patella_apex"], before["patella_target"],
                                        cfg["sigma_frac"] * W)
            lm["after"] = LM.knee_report(skin, warped, cfg["front"])
            rep["landmark"] = lm
        cv2.imwrite(os.path.join(out_dir, f"{name}.png"), cv2.cvtColor(warped, cv2.COLOR_RGB2BGR))
        wm = fg_mask(warped)
        med, p90 = chamfer(fg_mask(skin), wm)
        rep["layers"][name] = {"A": A.tolist(), "chamfer_median_px": round(med, 2), "chamfer_p90_px": round(p90, 2),
                               "raw_size": [raw.shape[1], raw.shape[0]], **info}
    mcp = os.path.join(asset_dir, "macro_crop.json")
    mraw = find("macro_raw", required=False)
    if os.path.exists(mcp) and mraw:
        bx, by, bs = json.load(open(mcp))["box_canvas"]
        bone = load_rgb(os.path.join(out_dir, "bone.png"))
        crop = bone[int(by):int(by + bs), int(bx):int(bx + bs)]
        macro = load_rgb(mraw)
        warp, cc, shift = register_macro(crop, macro)
        k = macro.shape[1] / crop.shape[1]
        Wm = warp.copy()
        Wm[:, 2] *= k
        mac_reg = cv2.warpAffine(macro, Wm, (macro.shape[1], macro.shape[0]),
                                 flags=cv2.INTER_CUBIC | cv2.WARP_INVERSE_MAP, borderMode=cv2.BORDER_REFLECT)
        cv2.imwrite(os.path.join(out_dir, "macro.png"), cv2.cvtColor(mac_reg, cv2.COLOR_RGB2BGR))
        rep["macro"] = {"box_canvas": [float(bx), float(by), float(bs)], "ecc": round(cc, 4),
                        "shift_crop_px": round(shift, 2), "size": [macro.shape[1], macro.shape[0]]}
    ms = fg_mask(skin)
    dbg = []
    for name in ("outer", "bone"):
        lay = load_rgb(os.path.join(out_dir, f"{name}.png"))
        ml = fg_mask(lay)
        v = (lay * 0.55).astype(np.uint8)
        v[edges(ms)] = (180, 255, 57)
        v[edges(ml)] = (255, 60, 200)
        dbg.append(v)
    cv2.imwrite(os.path.join(out_dir, "registration_debug.jpg"),
                cv2.cvtColor(np.concatenate([skin] + dbg, axis=1), cv2.COLOR_RGB2BGR), [cv2.IMWRITE_JPEG_QUALITY, 85])
    json.dump(rep, open(os.path.join(out_dir, "registration.json"), "w"), indent=1)
    return rep


if __name__ == "__main__":
    print(json.dumps(run(sys.argv[1]), indent=1))
